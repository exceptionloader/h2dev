#!/usr/bin/env bash
# Runs the offline server tests with the standalone Luau CLI.
#   LUAU=/path/to/luau ./tests/run.sh
set -euo pipefail
cd "$(dirname "$0")/.."
LUAU="${LUAU:-luau}"
out=tests/_sources.lua
{
  echo "-- generated by tests/run.sh, do not edit"
  echo "return {"
  for f in $(find src -name '*.lua' | sort); do
    if grep -q ']=====]' "$f"; then echo "cannot bundle $f" >&2; exit 1; fi
    printf '\t["./%s"] = [=====[\n' "$f"
    cat "$f"
    printf ']=====],\n'
  done
  echo "}"
} > "$out"
"$LUAU" tests/server_harness.lua
